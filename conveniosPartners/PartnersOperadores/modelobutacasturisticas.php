                  <h2 style="margin:0 0 10px 0; font-size:18px; color:#0056b3;">MODELO DE NEGOCIO BUTACAS TURÍSTICAS</h2>

                  <p style="margin:10px 0 0 0; font-weight:bold;">CONTEXTO GENERAL</p>
                  <p style="margin:6px 0 0 0;">
                    MeteleBrasil funcionaría como una plataforma digital de intermediación que conecta:
                  </p>
                  <ul style="margin:6px 0 0 20px;">
                    <li>Operadores o transportistas → que ya tienen buses charter a Brasil y butacas vacías.</li>
                    <li>Agencias o público final → que necesitan comprar esas butacas sueltas o armar paquetes.</li>
                  </ul>
                  <p style="margin:6px 0 0 0;">
                    El objetivo es optimizar la ocupación, formalizar el intercambio, y darle previsibilidad y trazabilidad al mercado informal que hoy opera “por debajo de la mesa”.
                  </p>

                  <p style="margin:12px 0 0 0; font-weight:bold;">⚙ ESTRUCTURA OPERATIVA</p>

                  <p style="margin:8px 0 0 0; font-weight:bold;">1. Acuerdo con Transportistas / Operadores</p>
                  <p style="margin:6px 0 0 0;">
                    Objetivo: que cedan un cupo mínimo de butacas por viaje (1, 2 o más) con un plazo de anticipación suficiente, y a cambio reciban visibilidad, ventas anticipadas y garantía de pago.
                  </p>
                  <p style="margin:6px 0 0 0;">Puntos clave a definir:</p>
                  <ul style="margin:6px 0 0 20px;">
                    <li>Anticipación mínima de entrega de cupos: 45 días (ideal: 60-90 días).</li>
                    <li>Cupo mínimo: 2 butacas por salida.</li>
                    <li>Precio neto acordado (con o sin comisión).</li>
                    <li>Condiciones de baja: si no se venden, si pueden reasignarse o si el operador puede retirarlas con aviso previo.</li>
                    <li>Responsabilidad de MeteleBrasil: venta, promoción, cobro y emisión de vouchers.</li>
                    <li>Responsabilidad del operador: cumplir salida, calidad del servicio, seguros, habilitaciones.</li>
                    <li>Política de reembolsos y penalidades.</li>
                    <li>Beneficio: prioridad en futuras campañas o mejor visibilidad en la plataforma si entregan cupos anticipados.</li>
                  </ul>

                  <p style="margin:8px 0 0 0; font-weight:bold;">2. Acuerdo con Agencias o Compradores Finales</p>
                  <p style="margin:6px 0 0 0;">
                    Objetivo: permitir que agencias más chicas o clientes finales compren butacas disponibles con seguridad y condiciones claras.
                  </p>
                  <p style="margin:6px 0 0 0;">Puntos clave a definir:</p>
                  <ul style="margin:6px 0 0 20px;">
                    <li>Condiciones de venta y cancelación (por ejemplo: cancelación sin cargo hasta X días antes).</li>
                    <li>Garantía de servicio: respaldo del operador validado por MeteleBrasil.</li>
                    <li>Condiciones de pago (anticipo, saldo, comisiones).</li>
                    <li>Responsabilidades de cada parte: MeteleBrasil como intermediario, no operador directo.</li>
                    <li>Protección frente a cambios o cancelaciones del transporte.</li>
                  </ul>
